function [lhs, rhs] = dynamic_resid(y, x, params, steady_state)
T = NaN(6, 1);
lhs = NaN(5, 1);
rhs = NaN(5, 1);
T(1) = params(1)/y(11);
T(2) = params(3)*exp(y(15))*y(12)^(params(3)-1);
T(3) = y(13)^(1-params(3));
T(4) = 1+T(2)*T(3)-params(4);
T(5) = exp(y(10))*y(7)^params(3);
T(6) = y(8)^(1-params(3));
lhs(1) = 1/y(6);
rhs(1) = T(1)*T(4);
lhs(2) = (1-params(3))*y(9)/y(6);
rhs(2) = 1/y(8);
lhs(3) = y(9);
rhs(3) = T(5)*T(6);
lhs(4) = y(7);
rhs(4) = y(9)+(1-params(4))*y(2)-y(6);
lhs(5) = y(10);
rhs(5) = params(2)*y(5)+params(5)*x(1);
end
